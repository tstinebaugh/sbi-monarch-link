#!/bin/bash
# install_native_host.sh
# Registers the SBI Monarch native messaging host with Chrome/Brave/Edge/Chromium/Arc on macOS.
#
# Usage:
#   bash native-host/install_native_host.sh [EXTENSION_ID]
#
# EXTENSION_ID is shown on chrome://extensions after you "Load unpacked".
# Unpacked extension IDs are derived from the folder path, so every install has its own ID.

set -euo pipefail

if [ "$(uname -s)" != "Darwin" ]; then
  echo "❌ This installer currently supports macOS only." >&2
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
HOST_NAME="com.sbi.monarch.host"
HOST_SCRIPT="$SCRIPT_DIR/sbi_monarch_host.py"
LAUNCHER_SCRIPT="$SCRIPT_DIR/sbi_monarch_host_launcher.sh"
MANIFEST_DEST="$SCRIPT_DIR/$HOST_NAME.json"

echo ""
echo "┌─────────────────────────────────────────────────┐"
echo "│  SBI Shinsei → Monarch Native Host Installer    │"
echo "└─────────────────────────────────────────────────┘"
echo ""

# ── Extension ID ──────────────────────────────────────────────────────────────
EXT_ID="${1:-}"
if [ -z "$EXT_ID" ] && [ -t 0 ]; then
  read -r -p "Paste your extension ID from chrome://extensions: " EXT_ID
fi
EXT_ID="$(echo "$EXT_ID" | tr -d '[:space:]')"
if ! [[ "$EXT_ID" =~ ^[a-p]{32}$ ]]; then
  echo "❌ Invalid extension ID '$EXT_ID'. Expected 32 lowercase letters a–p." >&2
  echo "   Usage: bash native-host/install_native_host.sh <EXTENSION_ID>" >&2
  exit 1
fi

# ── Python + dependencies ─────────────────────────────────────────────────────
PYTHON_PATH="$(python3 -c 'import sys; print(sys.executable)' 2>/dev/null || true)"
if [ -z "$PYTHON_PATH" ]; then
  echo "❌ python3 not found on PATH." >&2
  exit 1
fi
echo "Using Python: $PYTHON_PATH"
if ! "$PYTHON_PATH" -c 'import aiohttp, keyring, oathtool' 2>/dev/null; then
  echo "❌ Missing Python dependencies. Run first:" >&2
  echo "   $PYTHON_PATH -m pip install -r requirements.txt" >&2
  exit 1
fi

chmod +x "$HOST_SCRIPT"

# ── Launcher (Chrome starts hosts with a minimal environment) ─────────────────
cat > "$LAUNCHER_SCRIPT" <<EOF
#!/bin/bash
# Generated by install_native_host.sh — do not commit.
exec "$PYTHON_PATH" "$HOST_SCRIPT" "\$@"
EOF
chmod +x "$LAUNCHER_SCRIPT"

# ── Host manifest ─────────────────────────────────────────────────────────────
"$PYTHON_PATH" - "$MANIFEST_DEST" "$HOST_NAME" "$LAUNCHER_SCRIPT" "$EXT_ID" <<'PY'
import json, sys
dest, name, path, ext_id = sys.argv[1:5]
manifest = {
    "name": name,
    "description": "SBI Shinsei to Monarch Money native sync host",
    "path": path,
    "type": "stdio",
    "allowed_origins": [f"chrome-extension://{ext_id}/"],
}
with open(dest, "w") as f:
    json.dump(manifest, f, indent=2)
    f.write("\n")
PY

# ── Register with installed browsers ──────────────────────────────────────────
SUPPORT="$HOME/Library/Application Support"
installed=0
install_for_browser() {
  local profile_root="$1" name="$2"
  if [ -d "$profile_root" ]; then
    mkdir -p "$profile_root/NativeMessagingHosts"
    cp "$MANIFEST_DEST" "$profile_root/NativeMessagingHosts/$HOST_NAME.json"
    echo "✓ Installed for $name"
    installed=$((installed + 1))
  fi
}

install_for_browser "$SUPPORT/Google/Chrome"                 "Chrome"
install_for_browser "$SUPPORT/BraveSoftware/Brave-Browser"   "Brave"
install_for_browser "$SUPPORT/Microsoft Edge"                "Edge"
install_for_browser "$SUPPORT/Chromium"                      "Chromium"
install_for_browser "$SUPPORT/Arc/User Data"                 "Arc"

if [ "$installed" -eq 0 ]; then
  echo "⚠ No supported browser profile directories found; nothing registered." >&2
  exit 1
fi

echo ""
echo "✅ Native host installed for extension $EXT_ID"
echo ""
echo "Next: save your Monarch session via the extension popup, or run:"
echo "  $PYTHON_PATH $HOST_SCRIPT --session"
echo ""
echo "Then reload the extension in chrome://extensions."
